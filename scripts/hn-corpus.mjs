// Build the Hacker News practitioner corpus for Round H (docs/plans/build-guides.md §4b).
// Queries the public HN Algolia API for agent-building stories in a fixed window, keeps those
// above a points threshold, fetches the comment trees of the most-discussed threads, and writes:
//   docs/research/practitioners/.raw/<id>.json   full threads (gitignored: third-party comments)
//   docs/research/practitioners/corpus.md        the committed index (ids, links, metadata, queries)
// Usage: node scripts/hn-corpus.mjs [--max-threads 400] [--min-points 50]
// Behind an HTTPS proxy, set NODE_USE_ENV_PROXY=1 so Node's fetch uses HTTPS_PROXY.
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

const API = "https://hn.algolia.com/api/v1";
const FROM = Date.UTC(2025, 4, 18) / 1000; // 2025-05-18
const TO = Date.UTC(2026, 10, 18) / 1000; // 2026-11-18
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? Number(process.argv[i + 1]) : fallback;
};
const MAX_THREADS = arg("--max-threads", 400);
const MIN_POINTS = arg("--min-points", 50);
const QUERIES = [
  "AI agent",
  "AI agents",
  "agentic",
  "coding agent",
  "agent harness",
  "agent framework",
  "agent SDK",
  "building agents",
  "LLM agents",
  "MCP",
  "Model Context Protocol",
  "Claude Code",
  "Codex CLI",
  "Cursor agent",
  "Pi coding agent",
  "LangChain",
  "LangGraph",
  "AI SDK",
  "OpenAI Agents SDK",
  "Claude Agent SDK",
  "tool calling",
  "context engineering",
  "agent evals",
  "prompt injection",
  "subagents",
];
const OUT = "docs/research/practitioners";
const RAW = join(OUT, ".raw");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(url, tries = 4) {
  for (let i = 0; i < tries; i++) {
    const res = await fetch(url, { headers: { "user-agent": "buildanagent-research/1.0" } });
    if (res.ok) return res.json();
    await sleep(1000 * 2 ** i);
  }
  throw new Error(`GET failed: ${url}`);
}

// 1. Stories: every query, every page, inside the window and above the threshold.
const stories = new Map();
for (const q of QUERIES) {
  for (let page = 0; page < 10; page++) {
    const params = new URLSearchParams({
      query: q,
      tags: "story",
      // Match titles and URLs only: matching story text and comments pulls in unrelated threads.
      restrictSearchableAttributes: "title,url",
      // Exact matching: with typo tolerance on, "MCP" also matches "map" and "MC03".
      typoTolerance: "false",
      numericFilters: `created_at_i>=${FROM},created_at_i<${TO},points>=${MIN_POINTS}`,
      hitsPerPage: "100",
      page: String(page),
    });
    const data = await get(`${API}/search?${params}`);
    for (const h of data.hits) {
      const s = stories.get(h.objectID) ?? {
        id: h.objectID,
        title: h.title,
        url: h.url ?? null,
        date: h.created_at.slice(0, 10),
        points: h.points,
        comments: h.num_comments ?? 0,
        queries: [],
      };
      s.queries.push(q);
      stories.set(h.objectID, s);
    }
    if (page + 1 >= data.nbPages) break;
    await sleep(250);
  }
}

// 2. Threads: fetch comment trees for the most-discussed stories.
const ranked = [...stories.values()].sort((a, b) => b.comments - a.comments || b.points - a.points);
const picked = ranked.slice(0, MAX_THREADS);
await rm(RAW, { recursive: true, force: true });
await mkdir(RAW, { recursive: true });
const count = (node) => (node.children ?? []).reduce((n, c) => n + 1 + count(c), 0);
for (const s of picked) {
  const item = await get(`${API}/items/${s.id}`);
  s.fetchedComments = count(item);
  await writeFile(join(RAW, `${s.id}.json`), JSON.stringify(item));
  await sleep(200);
}

// 3. The committed index.
const rows = picked
  .sort((a, b) => a.date.localeCompare(b.date))
  .map(
    (s) =>
      `| ${s.date} | [${s.title.replace(/\|/g, "\\|")}](https://news.ycombinator.com/item?id=${s.id}) | ${s.points} | ${s.comments} | ${[...new Set(s.queries)].join(", ")} |`,
  );
const md = `# Hacker News corpus: agent-building threads, 2025-05-18 to 2026-11-18

*Generated by \`scripts/hn-corpus.mjs\` on ${new Date().toISOString().slice(0, 10)} from the public HN Algolia API. ${stories.size} stories with at least ${MIN_POINTS} points matched ${QUERIES.length} queries on their title or URL; the ${picked.length} most-commented are listed here and their comment trees were fetched into the gitignored \`.raw/\` folder (${picked.reduce((n, s) => n + (s.fetchedComments ?? 0), 0)} comments). Comments are third-party writing: the repo keeps links and metadata, and the theme notes quote only short attributed excerpts.*

Queries: ${QUERIES.map((q) => `\`${q}\``).join(", ")}.

| Date | Thread | Points | Comments | Matched queries |
|---|---|---|---|---|
${rows.join("\n")}
`;
await writeFile(join(OUT, "corpus.md"), md);
console.log(`${stories.size} stories matched; ${picked.length} threads fetched`);
