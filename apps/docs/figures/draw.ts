// Draws a registered figure with the book's svgkit, as figures:build writes it and the staleness test compares it.
import { pathToFileURL } from "node:url";
import { Figure } from "@buildanagent/manual/figures/svgkit";
import { type FigureId, fromRepo, scriptOf } from "./registry.js";

/**
 * The header comment the book's kit writes names the book's own build command. A docs figure is redrawn by the docs'
 * command, so the header is rewritten to name it; the rest of the file is the kit's, byte for byte. The header names
 * the command as the docs' figures:build script, not as `pnpm --filter …`, because XML forbids `--` inside a comment
 * and a file with one is not well-formed.
 */
const KIT_HEADER = /^<!-- Generated by [^\n]* -->\n/;

/** The header a docs figure's SVG starts with, naming the script that draws it and the command that redraws it. */
const headerOf = (id: FigureId): string =>
  `<!-- Generated by ${fromRepo(scriptOf(id))} with @buildanagent/manual/figures/svgkit. Do not edit: run the figures:build script of @buildanagent/docs. -->\n`;

/**
 * Runs one figure script in memory and returns the SVG it draws now. Throws when the script does not default-export a
 * function that returns a flat `Figure` whose id is the script's file name.
 */
export async function drawFigure(id: FigureId): Promise<string> {
  const module = (await import(pathToFileURL(scriptOf(id)).href)) as { default?: unknown };
  if (typeof module.default !== "function") {
    throw new Error(`${fromRepo(scriptOf(id))} must export default a function that returns its Figure`);
  }
  const drawn: unknown = module.default();
  if (!(drawn instanceof Figure)) throw new Error(`${fromRepo(scriptOf(id))} must return a Figure from svgkit`);
  if (drawn.id !== id) throw new Error(`${fromRepo(scriptOf(id))} draws figure "${drawn.id}", not "${id}"`);
  const svg = drawn.toSvg(fromRepo(scriptOf(id)));
  if (!KIT_HEADER.test(svg)) throw new Error("svgkit no longer starts its file with a header comment");
  const header = headerOf(id);
  if (header.slice(4, -4).includes("--"))
    throw new Error(`the header of figure "${id}" would hold --, which XML forbids`);
  return svg.replace(KIT_HEADER, header);
}
