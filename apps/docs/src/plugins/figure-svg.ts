/**
 * The check every committed figure SVG passes before a page inlines it. The SVGs are ours, drawn by the book's svgkit,
 * but a page inlines one as markup, so the check treats the file as untrusted: it reads the file tag by tag against an
 * allowlist of exactly what the kit writes, and anything else throws. Nothing is stripped or repaired. A file that
 * differs from the kit's output fails, so a hand edit or a crafted file can't put script, style or outside content on
 * a page.
 */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import type { Element, ElementContent, Properties } from "hast";

/**
 * The file as svgkit writes it: one header comment, the root `<svg>` tag, one `<style>` that makes the file render on
 * its own (the code font as a data URI and the panel tokens of both modes), then the drawing. The page drops that
 * style unread, since it serves the same font and tokens from its own stylesheets. The drawing is the only part that
 * reaches the page. The header holds no `--`, which XML forbids inside a comment, so a header with one fails here.
 */
const KIT_FILE =
  /^<!-- Generated by apps\/docs\/figures\/([a-z0-9]+(?:-[a-z0-9]+)*)\.ts with @buildanagent\/manual\/figures\/svgkit\. Do not edit: run the figures:build script of @buildanagent\/docs\. -->\n<svg ([^<>]*)>\n<style>\n([^<]*)\n<\/style>\n([\s\S]*)<\/svg>\n$/;

/** The root tag, exactly as the kit writes it: only its size and the figure's id vary. */
const ROOT =
  /^xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)" width="(\d+(?:\.\d+)?)" height="(\d+(?:\.\d+)?)" class="fig" data-figure="([a-z0-9-]+)"$/;

const NUMBER = /^-?\d+(?:\.\d+)?$/;
/** The pattern of `id` and `class`, which `propertiesOf` checks apart: ids by the figure's prefix, classes by name. */
const CHECKED_APART = /(?:)/;
/** The path commands the kit writes: moves, lines, quadratic curves and closes, with plain numbers. */
const PATH_DATA = /^[MLQ]-?\d+(?:\.\d+)? -?\d+(?:\.\d+)?(?: [MLQ]?-?\d+(?:\.\d+)? -?\d+(?:\.\d+)?)*(?: Z)?$/;

/**
 * Each element the kit draws, whether it closes itself, and the attributes it may carry with the value each may
 * take. `class` is checked apart, against the `fig-*` classes of the book's figures.css.
 */
const ELEMENTS: ReadonlyMap<
  string,
  { readonly selfClosing: boolean; readonly attributes: ReadonlyMap<string, RegExp> }
> = new Map([
  ["g", { selfClosing: false, attributes: new Map([["id", CHECKED_APART]]) }],
  [
    "rect",
    {
      selfClosing: true,
      attributes: new Map([
        ["x", NUMBER],
        ["y", NUMBER],
        ["width", NUMBER],
        ["height", NUMBER],
        ["rx", NUMBER],
        ["class", CHECKED_APART],
      ]),
    },
  ],
  [
    "path",
    {
      selfClosing: true,
      attributes: new Map([
        ["d", PATH_DATA],
        ["class", CHECKED_APART],
      ]),
    },
  ],
  [
    "circle",
    {
      selfClosing: true,
      attributes: new Map([
        ["cx", NUMBER],
        ["cy", NUMBER],
        ["r", NUMBER],
        ["class", CHECKED_APART],
      ]),
    },
  ],
  [
    "text",
    {
      selfClosing: false,
      attributes: new Map([
        ["x", NUMBER],
        ["y", NUMBER],
        ["text-anchor", /^(?:start|middle|end)$/],
        ["class", CHECKED_APART],
      ]),
    },
  ],
]);

/** hast's property names for the attributes whose names differ (hast spells them in camel case). */
const PROPERTY_NAMES: Readonly<Record<string, string>> = { "text-anchor": "textAnchor", class: "className" };

/** The entities the kit's `escapeXml` writes in a label, and the characters they stand for. */
const ENTITIES: Readonly<Record<string, string>> = { "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": '"' };

let figureClasses: ReadonlySet<string> | undefined;

/**
 * The `fig-*` classes the book's figures.css defines, which the docs load: the only classes a figure may use. Each
 * one colours through a panel token, so a figure that passes this check holds no colour of its own.
 */
export function knownFigureClasses(): ReadonlySet<string> {
  if (figureClasses !== undefined) return figureClasses;
  const css = readFileSync(createRequire(import.meta.url).resolve("@buildanagent/manual/styles/figures.css"), "utf8");
  figureClasses = new Set([...css.matchAll(/\.(fig-[a-z0-9-]+)/g)].map((match) => match[1] ?? ""));
  return figureClasses;
}

/** A figure SVG that failed the check; the message says what the file holds that the kit never writes. */
export class UnsafeFigureError extends Error {
  override readonly name = "UnsafeFigureError";
}

const fail = (message: string): never => {
  throw new UnsafeFigureError(message);
};

/** The attributes of a start tag, failing on one written any other way than `name="value"`, or written twice. */
function attributesOf(tag: string, source: string): Map<string, string> {
  const found = new Map<string, string>();
  const rest = source.replace(/ ([a-z][a-z-]*)="([^"<>&]*)"/g, (_, name: string, value: string) => {
    if (found.has(name)) fail(`its <${tag}> has the ${name} attribute twice`);
    found.set(name, value);
    return "";
  });
  if (rest !== "") fail(`its <${tag}> tag holds ${JSON.stringify(rest.slice(0, 40))}, which the kit never writes`);
  return found;
}

/** One element's attributes as hast properties, after each passed its element's allowlist. */
function propertiesOf(tag: string, attributes: Map<string, string>, figureId: string): Properties {
  const allowed = ELEMENTS.get(tag)?.attributes ?? new Map<string, RegExp>();
  const properties: Properties = {};
  for (const [name, value] of attributes) {
    const pattern = allowed.get(name);
    if (pattern === undefined) fail(`its <${tag}> has a ${name} attribute, which the kit never writes`);
    if (name === "id") {
      if (!new RegExp(`^${figureId}--[a-z0-9]+(?:-[a-z0-9]+)*$`).test(value)) {
        fail(`its id "${value}" does not start with "${figureId}--"`);
      }
    } else if (name === "class") {
      const classes = value.split(" ");
      const unknown = classes.find((name) => !knownFigureClasses().has(name));
      if (unknown !== undefined) fail(`its <${tag}> has the class "${unknown}", which figures.css does not define`);
    } else if (!pattern?.test(value)) {
      fail(`its <${tag}> has ${name}="${value.slice(0, 40)}", which is not a value the kit writes`);
    }
    properties[PROPERTY_NAMES[name] ?? name] = name === "class" ? value.split(" ") : value;
  }
  return properties;
}

/** A label's text, with the kit's four entities decoded. Any other `&`, and any `<` or `>`, throws. */
function labelText(token: string): string {
  if (/[<>]/.test(token)) fail("its text holds a < or > that the kit would have escaped");
  return token.replace(
    /&[^;]*;|&/g,
    (entity) => ENTITIES[entity] ?? fail(`its text holds ${entity}, an entity the kit never writes`),
  );
}

/**
 * Reads the drawing, the markup between the root's `<style>` and `</svg>`, into hast elements. Elements must be the
 * kit's, nest as the kit nests them and close; a comment, a CDATA section, a processing instruction or a doctype
 * fails wherever it stands, because none of them is an element the allowlist names.
 */
function drawingOf(markup: string, figureId: string): ElementContent[] {
  const root: ElementContent[] = [];
  const open: Element[] = [];
  for (const [token] of markup.matchAll(/<[^>]*>|[^<]+/g)) {
    const parent = open.at(-1);
    if (!token.startsWith("<")) {
      if (parent?.tagName === "text") parent.children.push({ type: "text", value: labelText(token) });
      else if (token.trim() !== "") fail("it holds text outside a <text> element");
      continue;
    }
    const closing = /^<\/([a-z]+)>$/.exec(token);
    if (closing !== null) {
      if (parent?.tagName !== closing[1]) fail(`its </${closing[1]}> closes no open element`);
      open.pop();
      continue;
    }
    const start = /^<([a-z]+)((?: [^>]*?)?)(\/?)>$/.exec(token);
    if (start === null) fail(`it holds ${JSON.stringify(token.slice(0, 40))}, which is not an element the kit writes`);
    const [, tag = "", source = "", slash = ""] = start ?? [];
    const kind = ELEMENTS.get(tag);
    if (kind === undefined) fail(`it holds a <${tag}> element, which the figure kit never draws`);
    if (kind?.selfClosing !== (slash === "/")) {
      fail(`its <${tag}> ${slash === "/" ? "closes itself" : "is left open"}, which the kit never writes`);
    }
    if (parent !== undefined && parent.tagName !== "g") fail(`its <${parent.tagName}> holds a <${tag}>`);
    const element: Element = {
      type: "element",
      tagName: tag,
      properties: propertiesOf(tag, attributesOf(tag, source), figureId),
      children: [],
    };
    (parent?.children ?? root).push(element);
    if (slash === "") open.push(element);
  }
  if (open.length > 0) fail(`its <${open.at(-1)?.tagName}> is never closed`);
  return root;
}

/**
 * A committed figure SVG as the hast `<svg>` element a page inlines: the kit's drawing, checked, named for screen
 * readers with `alt` (`role="img"` and `aria-label`), with the file's header comment and standalone `<style>` dropped.
 * Throws an `UnsafeFigureError` when the file is not svgkit's output for `figureId`, or holds anything the kit does not
 * write: any element besides `g`, `rect`, `path`, `circle` and `text`; any attribute or value besides the kit's; an
 * entity besides the four its labels use; or a class that figures.css does not define.
 */
export function figureSvg(text: string, options: { readonly figureId: string; readonly alt: string }): Element {
  const { figureId, alt } = options;
  const parts = KIT_FILE.exec(text);
  if (parts === null) fail("it is not a file that figures:build wrote with svgkit");
  const [, script = "", root = "", , drawing = ""] = parts ?? [];
  if (script !== figureId) fail(`its header names the script ${script}.ts, not ${figureId}.ts`);
  const size = ROOT.exec(root);
  if (size === null) fail("its <svg> tag is not the one svgkit writes");
  const [, viewWidth, viewHeight, width = "", height = "", drawn] = size ?? [];
  if (viewWidth !== width || viewHeight !== height) fail("its viewBox and its size disagree");
  if (drawn !== figureId) fail(`it was drawn for figure "${drawn}", not "${figureId}"`);
  return {
    type: "element",
    tagName: "svg",
    properties: {
      viewBox: `0 0 ${width} ${height}`,
      width,
      height,
      className: ["fig"],
      dataFigure: figureId,
      role: "img",
      ariaLabel: alt,
    },
    children: drawingOf(drawing, figureId),
  };
}
