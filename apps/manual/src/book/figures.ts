/** The parts of a figure kit SVG file: the header comment, the root tag, the style, then the drawing. */
const KIT_FILE = /^<!-- Generated by [^\n]* -->\n(<svg [^>]*>)\n<style>\n[\s\S]*?\n<\/style>\n([\s\S]*)<\/svg>\n$/;

/** The elements and attributes the figure kit writes inside its root, and so the only ones a page inlines. */
const KIT_ELEMENTS = new Set(["g", "rect", "path", "circle", "text"]);
const KIT_ATTRIBUTES = new Set(["id", "class", "x", "y", "width", "height", "rx", "d", "cx", "cy", "r", "text-anchor"]);
const LINK_ATTRIBUTES = new Set(["href", "xlink:href"]);
const ROOT_ATTRIBUTES = new Set(["xmlns", "viewBox", "width", "height", "class", "data-figure"]);

/** The attributes of a start tag, failing on one written another way than `name="value"`. */
function attributesOf(tag: string, source: string): [name: string, value: string][] {
  const found: [string, string][] = [];
  const rest = source.replace(/\s+([A-Za-z_:][\w:.-]*)="([^"<]*)"/g, (_, name: string, value: string) => {
    found.push([name, value]);
    return "";
  });
  if (rest.trim() !== "" && rest.trim() !== "/") throw new Error(`its <${tag}> tag is malformed`);
  return found;
}

/**
 * Checks the drawing inside a kit SVG's root, tag by tag, and rewrites its ids and `#id` links with `idPrefix`. Only
 * the kit's elements and attributes pass: an event handler, a link to anything but an id in this figure, a script,
 * a `foreignObject`, an image, a second style, a comment or an unknown entity each throw, so a hand-edited or crafted
 * file cannot put script or outside content on a page.
 */
function checkedDrawing(drawing: string, figureId: string, idPrefix: string): string {
  const open: string[] = [];
  const checked = drawing.replace(/<[^>]*>|[^<]+/g, (token) => {
    if (!token.startsWith("<")) {
      if (/&(?!amp;|lt;|gt;|quot;)/.test(token)) throw new Error("its text holds an entity the kit never writes");
      return token;
    }
    const closing = /^<\/([A-Za-z][\w:-]*)>$/.exec(token);
    if (closing !== null) {
      if (open.pop() !== closing[1]) throw new Error(`its </${closing[1]}> closes no open element`);
      return token;
    }
    const start = /^<([A-Za-z][\w:-]*)([^>]*?)(\/?)>$/.exec(token);
    const [, tag = "", source = "", selfClosing = ""] = start ?? [];
    if (start === null) throw new Error(`it holds ${token.slice(0, 20)}, which is not an element the kit writes`);
    if (!KIT_ELEMENTS.has(tag)) throw new Error(`it holds a <${tag}> element, which the figure kit never draws`);
    const rewritten = attributesOf(tag, source).map(([name, value]) => {
      if (/^on/i.test(name)) throw new Error(`its <${tag}> has an event handler, ${name}`);
      if (LINK_ATTRIBUTES.has(name)) {
        if (!value.startsWith(`#${figureId}--`)) throw new Error(`its <${tag}> links to ${value}, not to an id in it`);
        return ` ${name}="#${idPrefix}${value.slice(1)}"`;
      }
      if (!KIT_ATTRIBUTES.has(name))
        throw new Error(`its <${tag}> has a ${name} attribute, which the kit never writes`);
      if (name === "id") {
        if (!value.startsWith(`${figureId}--`))
          throw new Error(`its id "${value}" does not start with "${figureId}--"`);
        return ` id="${idPrefix}${value}"`;
      }
      return ` ${name}="${value}"`;
    });
    if (selfClosing === "") open.push(tag);
    return `<${tag}${rewritten.join("")}${selfClosing}>`;
  });
  if (open.length > 0) throw new Error(`its <${open.at(-1)}> is never closed`);
  return checked;
}

/**
 * A figure kit SVG, ready to inline in a page. It drops the header comment and the `<style>` element, because the page
 * serves the same font and colours from its own stylesheets and its content security policy allows no inline style.
 * It names the drawing for screen readers with `alt`, and prefixes every id and `#id` link with `idPrefix` when one page
 * shows the figure twice, as the gallery does. Throws, saying what is wrong, when the file is not a kit SVG for this
 * figure, or when its drawing holds anything the kit does not write (see `checkedDrawing`).
 */
export function inlineSvg(
  text: string,
  options: { readonly figureId: string; readonly alt: string; readonly idPrefix?: string },
): string {
  const { figureId, alt, idPrefix = "" } = options;
  const parts = KIT_FILE.exec(text);
  if (parts === null) throw new Error("it was not written by figures/lib/svgkit.ts");
  const [, root = "", drawing = ""] = parts;
  const rootAttributes = new Map(attributesOf("svg", root.slice("<svg".length, -1)));
  const unknown = [...rootAttributes.keys()].find((name) => !ROOT_ATTRIBUTES.has(name));
  if (unknown !== undefined) throw new Error(`its <svg> has a ${unknown} attribute, which the kit never writes`);
  const drawn = rootAttributes.get("data-figure");
  if (drawn !== figureId) throw new Error(`it was drawn for figure "${drawn ?? ""}", not "${figureId}"`);
  const named = root.replace(/>$/, ` role="img" aria-label="${escapeXml(alt)}">`);
  return `${named}\n${checkedDrawing(drawing, figureId, idPrefix)}</svg>`;
}

/** The header comment figures/lib/isokit.ts writes on the first line of a fragment, naming its figure. */
const FRAGMENT_FILE =
  /^<!-- Generated by apps\/manual\/figures\/lib\/isokit\.ts from [^\n]* for figure "([a-z0-9-]+)"\. [^\n]* -->\n(<figure class="iso-figure">[\s\S]*<\/figure>)\n$/;

const SVG_NAMESPACE = "http://www.w3.org/2000/svg";

/**
 * The elements a fragment may hold and the attributes each may carry, besides `class`, `id` and `data-*`, which any of
 * them may carry. They are what the anatomy kit's `plateHtml`, `figureSvg`, `solidSvg`, `lineSvg`, `wireSvg`,
 * `dotsSvg`, `fadedSvg`, `faceTextSvg`, `groupSvg` and `tubeSvg` write, less three things the page's content security
 * policy or the book cannot take: a `style` attribute (`fadeLineSvg` and pulsing dots write one), the kit's legend
 * (the chapter's caption replaces it) and the `<style>` of a standalone SVG.
 */
const FRAGMENT_ELEMENTS: ReadonlyMap<string, ReadonlySet<string>> = new Map([
  ["figure", new Set<string>()],
  ["div", new Set(["aria-hidden"])],
  ["span", new Set(["aria-hidden"])],
  ["svg", new Set(["xmlns", "viewBox", "width", "height", "role", "aria-label"])],
  ["g", new Set(["transform", "opacity"])],
  ["path", new Set(["d", "transform", "opacity"])],
  ["circle", new Set(["cx", "cy", "r", "opacity", "fill-opacity"])],
  ["text", new Set(["transform", "font-size", "text-anchor"])],
]);
const NUMBER = String.raw`-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?`;
/** The value each presentation attribute may take: numbers, path data or transform functions, never a url(). */
const FRAGMENT_VALUES: ReadonlyMap<string, RegExp> = new Map([
  ["class", /^[a-z][a-z0-9_ -]*$/],
  ["aria-hidden", /^true$/],
  ["xmlns", new RegExp(`^${SVG_NAMESPACE.replace(/[./]/g, "\\$&")}$`)],
  ["viewBox", new RegExp(`^${NUMBER}(?: ${NUMBER}){3}$`)],
  ["d", /^[MmLlHhVvCcSsQqTtAaZz0-9.,eE+\s-]*$/],
  ["transform", new RegExp(`^(?:(?:matrix|translate|scale|rotate)\\((?:${NUMBER}[ ,]*)+\\)\\s*)+$`)],
  ["text-anchor", /^(?:start|middle|end)$/],
  ["role", /^img$/],
]);
const NUMERIC = new Set(["width", "height", "cx", "cy", "r", "opacity", "fill-opacity", "font-size"]);

interface FragmentContext {
  readonly figureId: string;
  readonly idPrefix: string;
}

/** Checks one attribute of a fragment element and returns it as the page should carry it, its id prefixed. */
function fragmentAttribute(tag: string, name: string, value: string, context: FragmentContext): string {
  const { figureId, idPrefix } = context;
  if (/^on/i.test(name)) throw new Error(`its <${tag}> has an event handler, ${name}`);
  if (name === "id") {
    if (!value.startsWith(`${figureId}--`)) throw new Error(`its id "${value}" does not start with "${figureId}--"`);
    return ` id="${idPrefix}${value}"`;
  }
  if (/^data-[a-z][a-z0-9-]*$/.test(name)) return ` ${name}="${value}"`;
  if (name !== "class" && !FRAGMENT_ELEMENTS.get(tag)?.has(name)) {
    throw new Error(`its <${tag}> has a ${name} attribute, which the fragment allowlist does not take`);
  }
  const pattern = FRAGMENT_VALUES.get(name);
  const valid = NUMERIC.has(name) ? new RegExp(`^${NUMBER}$`).test(value) : (pattern?.test(value) ?? true);
  if (!valid) throw new Error(`its <${tag}> has ${name}="${value.slice(0, 40)}", which is not a value the kit writes`);
  return ` ${name}="${value}"`;
}

/** Which elements may hold which: the figure holds HTML, the plate holds one SVG, and the SVG holds only SVG. */
function checkNesting(tag: string, open: readonly string[], seen: { svg: number; root: boolean }): void {
  const parent = open.at(-1);
  const inSvg = open.includes("svg");
  if (parent === undefined) throw new Error(`it holds a <${tag}> outside its <figure class="iso-figure">`);
  if (tag === "figure") throw new Error("it holds a second <figure>");
  if (tag === "svg") {
    seen.svg += 1;
    if (inSvg || seen.svg > 1) throw new Error("it holds more than one <svg>; a fragment draws one drawing");
  } else if (inSvg !== ["g", "path", "circle", "text"].includes(tag)) {
    throw new Error(`it holds a <${tag}> ${inSvg ? "inside" : "outside"} its <svg>`);
  }
  if (["path", "circle"].includes(parent)) throw new Error(`its <${parent}> holds a <${tag}>`);
}

/**
 * An isometric figure's HTML fragment, ready to inline in a chapter: the card the anatomy kit's `plateHtml` writes
 * around one `figureSvg` drawing. The fragment is checked tag by tag against an allowlist built from what the kit
 * writes (see FRAGMENT_ELEMENTS): a script, a style element or attribute, an iframe, an image, an event handler, a
 * link, a comment past the header, an entity the kit never writes or a `url()` in any value throws, so a hand-edited or
 * crafted fragment cannot put script or outside content on a page. The page gets the card as a `<div>`, because the
 * chapter's own `<figure>` holds it and its caption; the drawing is hidden from screen readers, which read the alt text
 * from the hidden paragraph the caller puts before it; every id takes `idPrefix`, so one page can show two fragments;
 * and the card's figure corner shows `number` when one is given.
 */
export function inlineFragment(
  text: string,
  options: { readonly figureId: string; readonly idPrefix?: string; readonly number?: string },
): string {
  const { figureId, idPrefix = "", number } = options;
  const parts = FRAGMENT_FILE.exec(text);
  if (parts === null) throw new Error("it was not written by figures/lib/isokit.ts");
  const [, drawn = "", fragment = ""] = parts;
  if (drawn !== figureId) throw new Error(`it was drawn for figure "${drawn}", not "${figureId}"`);
  const context = { figureId, idPrefix };
  const open: string[] = [];
  const seen = { svg: 0, root: false };
  const checked = fragment.replace(/<[^>]*>|[^<]+/g, (token) => {
    if (!token.startsWith("<")) {
      if (open.length === 0) throw new Error('it holds text outside its <figure class="iso-figure">');
      if (/&(?!amp;|lt;|gt;|quot;)/.test(token)) throw new Error("its text holds an entity the kit never writes");
      return token;
    }
    const closing = /^<\/([A-Za-z][\w:-]*)>$/.exec(token);
    if (closing !== null) {
      if (open.pop() !== closing[1]) throw new Error(`its </${closing[1]}> closes no open element`);
      return closing[1] === "figure" ? "</div>" : token;
    }
    if (open.length === 0 && seen.root) throw new Error("it holds a second <figure> after its card");
    const start = /^<([A-Za-z][\w:-]*)([^>]*?)(\/?)>$/.exec(token);
    const [, tag = "", source = "", selfClosing = ""] = start ?? [];
    if (start === null) throw new Error(`it holds ${token.slice(0, 20)}, which is not an element the kit writes`);
    if (!FRAGMENT_ELEMENTS.has(tag))
      throw new Error(`it holds a <${tag}> element, which the fragment allowlist does not take`);
    if (open.length === 0 && tag !== "figure")
      throw new Error(`it holds a <${tag}> outside its <figure class="iso-figure">`);
    if (open.length > 0) checkNesting(tag, open, seen);
    // The kit writes one boolean attribute bare, the card's data-readout; give it the empty value it means.
    const attributes = attributesOf(tag, source.replace(/\s(data-[a-z][a-z0-9-]*)(?=\s|\/|$)/g, ' $1=""'));
    let rewritten = attributes.map(([name, value]) => fragmentAttribute(tag, name, value, context)).join("");
    if (tag === "figure") {
      seen.root = true;
      if (rewritten !== ' class="iso-figure"') throw new Error('its root must be <figure class="iso-figure">');
      rewritten = ` class="iso-figure" data-figure="${figureId}"`;
    }
    if (tag === "svg") rewritten = `${rewritten.replace(/ (role|aria-label)="[^"]*"/g, "")} aria-hidden="true"`;
    if (selfClosing === "") open.push(tag);
    return `<${tag === "figure" ? "div" : tag}${rewritten}${selfClosing}>`;
  });
  if (open.length > 0) throw new Error(`its <${open.at(-1)}> is never closed`);
  if (seen.svg === 0) throw new Error("it holds no <svg> drawing");
  if (number === undefined) return checked;
  return checked.replace(
    /(<span class="iso-plate-corner" data-corner="fig">)[^<]*(<\/span>)/,
    (_, before: string, after: string) => `${before}${escapeXml(number)}${after}`,
  );
}
