/**
 * Where a figure's generated files live, beside its script `<figures dir>/<chapter slug>/<figure id>.ts`: a flat
 * figure writes `<figure id>.svg`, and an isometric figure writes the HTML fragment `<figure id>.html`.
 */
export const figureFiles = (
  figuresDir: string,
  slug: string,
  id: string,
): { svg: string; fragment: string; script: string } => ({
  svg: join(figuresDir, slug, `${id}.svg`),
  fragment: join(figuresDir, slug, `${id}.html`),
  script: join(figuresDir, slug, `${id}.ts`),
});

/** The parts of a figure kit SVG file: the header comment, the root tag, the style, then the drawing. */
const KIT_FILE = /^<!-- Generated by [^\n]* -->\n(<svg [^>]*>)\n<style>\n[\s\S]*?\n<\/style>\n([\s\S]*)<\/svg>\n$/;

/** The elements and attributes the figure kit writes inside its root, and so the only ones a page inlines. */
const KIT_ELEMENTS = new Set(["g", "rect", "path", "circle", "text"]);
const KIT_ATTRIBUTES = new Set(["class", "x", "y", "width", "height", "rx", "d", "cx", "cy", "r", "text-anchor"]);
const LINK_ATTRIBUTES = new Set(["href", "xlink:href"]);
const ROOT_ATTRIBUTES = new Set(["xmlns", "viewBox", "width", "height", "class", "data-figure"]);

/**
 * The flat figure kit's allowlist: its five elements and their attributes, and links only to ids in this figure, which
 * take the id prefix. A script, a `foreignObject`, an image, a second style or a link elsewhere throws.
 */
const flatRules = (figureId: string, idPrefix: string): MarkupRules => ({
  figureId,
  idPrefix,
  element: (tag) => {
    if (!KIT_ELEMENTS.has(tag)) throw new Error(`it holds a <${tag}> element, which the figure kit never draws`);
  },
  attribute: (tag, name, value) => {
    if (LINK_ATTRIBUTES.has(name)) {
      if (!value.startsWith(`#${figureId}--`)) throw new Error(`its <${tag}> links to ${value}, not to an id in it`);
      return `${name}="#${idPrefix}${value.slice(1)}"`;
    }
    if (!KIT_ATTRIBUTES.has(name)) throw new Error(`its <${tag}> has a ${name} attribute, which the kit never writes`);
    return `${name}="${value}"`;
  },
});

/**
 * A figure kit SVG, ready to inline in a page. It drops the header comment and the `<style>` element, because the page
 * serves the same font and colours from its own stylesheets and its content security policy allows no inline style.
 * It names the drawing for screen readers with `alt`, and prefixes every id and `#id` link with `idPrefix` when one
 * page shows the figure twice, as the gallery does. Throws, saying what is wrong, when the file is not a kit SVG for
 * this figure, or when its drawing holds anything the kit does not write (see `flatRules` and `checkMarkup`).
 */
export function inlineSvg(
  text: string,
  options: { readonly figureId: string; readonly alt: string; readonly idPrefix?: string },
): string {
  const { figureId, alt, idPrefix = "" } = options;
  const parts = KIT_FILE.exec(text);
  if (parts === null) throw new Error("it was not written by figures/lib/svgkit.ts");
  const [, root = "", drawing = ""] = parts;
  const rootAttributes = new Map(attributesOf("svg", root.slice("<svg".length, -1)));
  const unknown = [...rootAttributes.keys()].find((name) => !ROOT_ATTRIBUTES.has(name));
  if (unknown !== undefined) throw new Error(`its <svg> has a ${unknown} attribute, which the kit never writes`);
  const drawn = rootAttributes.get("data-figure");
  if (drawn !== figureId) throw new Error(`it was drawn for figure "${drawn ?? ""}", not "${figureId}"`);
  const named = root.replace(/>$/, ` role="img" aria-label="${escapeXml(alt)}">`);
  return `${named}\n${checkMarkup(drawing, flatRules(figureId, idPrefix))}</svg>`;
}

/** The header comment figures/lib/isokit.ts writes on the first line of a fragment, naming its figure. */
const FRAGMENT_FILE = new RegExp(
  String.raw`^<!-- Generated by apps\/manual\/figures\/lib\/isokit\.ts from [^\n]* for figure "([a-z0-9-]+)"\. ` +
    String.raw`[^\n]* -->\n(<figure class="iso-figure">[\s\S]*<\/figure>)\n$`,
);

const SVG_NAMESPACE = "http://www.w3.org/2000/svg";
const SVG_ELEMENTS = new Set(["g", "path", "circle", "text"]);

/**
 * The elements a fragment may hold and the attributes each may carry besides `class`, `id` and the `data-*` attributes
 * in FRAGMENT_DATA. They are what the anatomy kit's `plateHtml`, `figureSvg`, `solidSvg`, `lineSvg`, `wireSvg`,
 * `dotsSvg`, `fadedSvg`, `faceTextSvg`, `groupSvg` and `tubeSvg` write, less three things the page's content security
 * policy or the book cannot take: a `style` attribute (`fadeLineSvg` and pulsing dots write one), the kit's legend
 * (the chapter's caption replaces it) and the `<style>` of a standalone SVG.
 */
const FRAGMENT_ELEMENTS: ReadonlyMap<string, ReadonlySet<string>> = new Map([
  ["figure", new Set<string>()],
  ["div", new Set(["aria-hidden"])],
  ["span", new Set(["aria-hidden"])],
  ["svg", new Set(["xmlns", "viewBox", "width", "height", "role", "aria-label"])],
  ["g", new Set(["transform", "opacity"])],
  ["path", new Set(["d", "transform", "opacity"])],
  ["circle", new Set(["cx", "cy", "r", "opacity", "fill-opacity"])],
  ["text", new Set(["transform", "font-size", "text-anchor"])],
]);
const NUMBER = String.raw`-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?`;
/** The value each presentation attribute may take: numbers, path data or transform functions, never a url(). */
const FRAGMENT_VALUES: ReadonlyMap<string, RegExp> = new Map([
  ["class", /^[a-z][a-z0-9_ -]*$/],
  ["aria-hidden", /^true$/],
  ["xmlns", new RegExp(`^${SVG_NAMESPACE.replace(/[./]/g, "\\$&")}$`)],
  ["viewBox", new RegExp(`^${NUMBER}(?: ${NUMBER}){3}$`)],
  ["d", /^[MmLlHhVvCcSsQqTtAaZz0-9.,eE+\s-]*$/],
  ["transform", new RegExp(`^(?:(?:matrix|translate|scale|rotate)\\((?:${NUMBER}[ ,]*)+\\)\\s*)+$`)],
  ["text-anchor", /^(?:start|middle|end)$/],
  ["role", /^img$/],
  ...["width", "height", "cx", "cy", "r", "opacity", "fill-opacity", "font-size"].map((name): [string, RegExp] => [
    name,
    new RegExp(`^${NUMBER}$`),
  ]),
]);

/**
 * The `data-*` attributes a fragment may carry, each with the values it may take: the kit's tones, shades, flags and
 * card corners; the part names `isokit.ts` writes; and the two that src/scripts/iso-figures.ts reads, a step number
 * and the readout text it shows through `textContent`. Any other `data-*` attribute, or another value, throws.
 */
const FRAGMENT_DATA: ReadonlyMap<string, RegExp> = new Map([
  ["data-tone", /^(?:hi|mid|lo|faint|lit|red|green|blue)$/],
  ["data-shade", /^[0-3]$/],
  ["data-lit", /^$/],
  ["data-seamless", /^$/],
  ["data-dotted", /^$/],
  ["data-dashed", /^$/],
  ["data-flow", /^$/],
  ["data-readout", /^$/],
  ["data-free", /^(?:|start|end)$/],
  ["data-corner", /^(?:fig|title|hint|readout)$/],
  ["data-part", /^[a-z0-9.#-]+$/],
  ["data-iso-step", /^\d{1,2}$/],
  ["data-iso-readout", /^[\p{L}\p{N} .,:;·()/+%–-]*$/u],
]);

/** The isometric kit's allowlist: the card, then one drawing inside it, then nothing after the card. */
function fragmentRules(figureId: string, idPrefix: string): MarkupRules {
  let cards = 0;
  let drawings = 0;
  return {
    figureId,
    idPrefix,
    bare: ["data-readout"],
    element: (tag, open, selfClosing) => {
      if (!FRAGMENT_ELEMENTS.has(tag)) {
        throw new Error(`it holds a <${tag}> element, which the fragment allowlist does not take`);
      }
      const parent = open.at(-1);
      const inSvg = open.includes("svg");
      if (tag === "figure") {
        cards += 1;
        if (parent !== undefined || cards > 1) throw new Error("it holds a second <figure>; a fragment is one card");
        return;
      }
      if (parent === undefined) throw new Error(`it holds a <${tag}> outside its <figure class="iso-figure">`);
      if (selfClosing && !inSvg) throw new Error(`its <${tag}/> closes itself outside the <svg>, which HTML ignores`);
      if (tag === "svg") {
        drawings += 1;
        if (inSvg || drawings > 1) throw new Error("it holds more than one <svg>; a fragment draws one drawing");
      } else if (inSvg !== SVG_ELEMENTS.has(tag)) {
        throw new Error(`it holds a <${tag}> ${inSvg ? "inside" : "outside"} its <svg>`);
      }
      if (parent === "path" || parent === "circle") throw new Error(`its <${parent}> holds a <${tag}>`);
    },
    attribute: (tag, name, value) => {
      const data = FRAGMENT_DATA.get(name);
      const allowed = name === "class" || name.startsWith("data-") || FRAGMENT_ELEMENTS.get(tag)?.has(name);
      if (!allowed || (name.startsWith("data-") && data === undefined)) {
        throw new Error(`its <${tag}> has a ${name} attribute, which the fragment allowlist does not take`);
      }
      const pattern = data ?? FRAGMENT_VALUES.get(name);
      if (pattern !== undefined && !pattern.test(value)) {
        throw new Error(`its <${tag}> has ${name}="${value.slice(0, 40)}", which is not a value the kit writes`);
      }
      return `${name}="${value}"`;
    },
    text: (text, open) => {
      if (open.length === 0) throw new Error(`it holds text outside its <figure class="iso-figure">`);
      if (open.at(-1) === "svg" || open.at(-1) === "g") {
        if (text.trim() !== "") throw new Error("it holds text in its drawing outside a <text> element");
      }
    },
    startTag: (tag, attributes, selfClosing) => {
      if (tag === "figure") {
        if (attributes !== ' class="iso-figure"') throw new Error('its root must be <figure class="iso-figure">');
        return `<div class="iso-figure" data-figure="${figureId}">`;
      }
      // The chapter reads the alt text from the paragraph before the card, so the drawing itself is hidden.
      const shown =
        tag === "svg" ? `${attributes.replace(/ (role|aria-label)="[^"]*"/g, "")} aria-hidden="true"` : attributes;
      return `<${tag}${shown}${selfClosing ? "/" : ""}>`;
    },
    endTag: (tag) => (tag === "figure" ? "</div>" : `</${tag}>`),
  };
}

/**
 * An isometric figure's HTML fragment, ready to inline in a chapter: the card the anatomy kit's `plateHtml` writes
 * around one `figureSvg` drawing. The fragment is checked tag by tag (`checkMarkup`) against an allowlist built from
 * what the kit writes (FRAGMENT_ELEMENTS, FRAGMENT_VALUES and FRAGMENT_DATA), so a hand-edited or crafted fragment
 * cannot put script or outside content on a page. The page gets the card as a `<div>`, because the chapter's own
 * `<figure>` holds it and its caption; the drawing is hidden from screen readers, which read the alt text from the
 * hidden paragraph the caller puts before it; every id takes `idPrefix`, so one page can show a figure twice; and the
 * card's figure corner shows `number` when one is given.
 */
export function inlineFragment(
  text: string,
  options: { readonly figureId: string; readonly idPrefix?: string; readonly number?: string },
): string {
  const { figureId, idPrefix = "", number } = options;
  const parts = FRAGMENT_FILE.exec(text);
  if (parts === null) throw new Error("it was not written by figures/lib/isokit.ts");
  const [, drawn = "", fragment = ""] = parts;
  if (drawn !== figureId) throw new Error(`it was drawn for figure "${drawn}", not "${figureId}"`);
  const checked = checkMarkup(fragment, fragmentRules(figureId, idPrefix));
  if (!checked.includes("<svg ")) throw new Error("it holds no <svg> drawing");
  if (number === undefined) return checked;
  return checked.replace(
    /(<span class="iso-plate-corner" data-corner="fig">)[^<]*(<\/span>)/,
    (_, before: string, after: string) => `${before}${escapeXml(number)}${after}`,
  );
}

/** What a figure kind inlines with: its figure's id and alt text, the page's id prefix and the figure's number. */
export interface InlineOptions {
  readonly figureId: string;
  readonly alt: string;
  readonly idPrefix?: string;
  readonly number?: string;
}

/**
 * The two kinds of generated figure, keyed by the directive a chapter places each with: the file each script writes
 * beside itself (a key of `figureFiles`) and how a page inlines it. A flat figure's SVG is named by its alt text; an
 * isometric figure's fragment follows its alt text, kept as a visually hidden paragraph, and shows its number.
 */
export const FIGURE_KINDS = {
  svg: {
    file: "svg",
    inline: (text: string, { figureId, alt, idPrefix }: InlineOptions): string =>
      inlineSvg(text, { figureId, alt, ...(idPrefix ? { idPrefix } : {}) }),
  },
  viewer: {
    file: "fragment",
    inline: (text: string, { figureId, alt, idPrefix, number }: InlineOptions): string => {
      const card = inlineFragment(text, {
        figureId,
        ...(idPrefix ? { idPrefix } : {}),
        ...(number ? { number: `Figure ${number}` } : {}),
      });
      return `<p class="visually-hidden">${escapeXml(alt)}</p>${card}`;
    },
  },
} as const satisfies Record<
  string,
  { readonly file: "svg" | "fragment"; readonly inline: (text: string, options: InlineOptions) => string }
>;

/** The directive a chapter places a generated figure with: `::svg` or `::viewer`. */
export type FigureDirective = keyof typeof FIGURE_KINDS;

export const isFigureDirective = (name: string): name is FigureDirective => Object.hasOwn(FIGURE_KINDS, name);
