// Tests for offline-verify-deployed.mjs against a local static server: a deploy that matches its list, one whose page
// a CDN rewrote but that keeps the build's mark, and one with a changed script, a missing file and an old worker.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { createServer } from "node:http";
import { test } from "node:test";
import { verifyDeployed } from "./offline-verify-deployed.mjs";

const BUILD = "0123456789abcdef";
const PAGE = `<!doctype html><html><head><meta name="manual-build" content="${BUILD}"></head><body>bob@example.com</body></html>`;
const SCRIPT = "console.log('notes');";
// As the build does, a page is listed with the placeholder in its build mark.
const entry = (url, path, text) => {
  const listed = path.endsWith(".html") ? text.replace(BUILD, "__MANUAL_BUILD__") : text;
  return { url, path, size: Buffer.byteLength(listed), sha256: createHash("sha256").update(listed).digest("hex") };
};
const LIST = {
  version: 2,
  build: BUILD,
  files: [entry("/tools/", "tools/index.html", PAGE), entry("/scripts/notes.js", "scripts/notes.js", SCRIPT)],
};

async function serve(routes) {
  const server = createServer((request, response) => {
    const body = routes[request.url ?? ""];
    if (body === undefined) response.writeHead(404).end("not found");
    else response.writeHead(200).end(body);
  });
  await new Promise((done) => server.listen(0, "127.0.0.1", done));
  return { origin: `http://127.0.0.1:${server.address().port}`, close: () => server.close() };
}

const worker = `// The book's service worker for build ${BUILD}, generated by scripts/offline-build.mjs (ADR 0059).\n`;

test("a deploy whose files match its list byte for byte passes", async () => {
  const site = await serve({
    "/offline-manifest.json": JSON.stringify(LIST),
    "/sw.js": worker,
    "/tools/": PAGE,
    "/scripts/notes.js": SCRIPT,
  });
  try {
    const result = await verifyDeployed(site.origin);
    assert.deepEqual(result.ok, ["/tools/", "/scripts/notes.js"]);
    assert.deepEqual(result.rewritten, []);
    assert.deepEqual(result.failed, []);
  } finally {
    site.close();
  }
});

test("a page a CDN rewrote is reported as rewritten while it keeps the build's mark", async () => {
  const rewritten = PAGE.replace(
    "bob@example.com",
    '<a href="/cdn-cgi/l/email-protection#1">[email protected]</a><script src="/cdn-cgi/scripts/email-decode.min.js"></script>',
  );
  const site = await serve({
    "/offline-manifest.json": JSON.stringify(LIST),
    "/sw.js": worker,
    "/tools/": rewritten,
    "/scripts/notes.js": SCRIPT,
  });
  try {
    const result = await verifyDeployed(site.origin);
    assert.deepEqual(result.rewritten, ["/tools/"]);
    assert.deepEqual(result.failed, []);
  } finally {
    site.close();
  }
});

test("a changed script, a missing file, a page without the mark and an old worker each fail", async () => {
  const site = await serve({
    "/offline-manifest.json": JSON.stringify(LIST),
    "/sw.js": worker.replace(BUILD, "fedcba9876543210"),
    "/tools/": PAGE.replace(BUILD, "fedcba9876543210"),
  });
  try {
    const result = await verifyDeployed(site.origin);
    assert.deepEqual(
      result.failed.map((problem) => problem.path),
      ["/sw.js", "/tools/", "/scripts/notes.js"],
    );
    assert.match(result.failed[2].reason, /status 404/);
  } finally {
    site.close();
  }
});
